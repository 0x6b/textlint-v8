use std::{
    fs::{create_dir_all, write},
    path::Path,
};

use anyhow::{Context, Result};

const DICTIONARY_FILES: [&str; 12] = [
    "base.dat.gz",
    "check.dat.gz",
    "tid.dat.gz",
    "tid_pos.dat.gz",
    "tid_map.dat.gz",
    "cc.dat.gz",
    "unk.dat.gz",
    "unk_pos.dat.gz",
    "unk_map.dat.gz",
    "unk_char.dat.gz",
    "unk_compat.dat.gz",
    "unk_invoke.dat.gz",
];

pub fn write_placeholder_assets(out_dir: &Path) -> Result<()> {
    write(
        out_dir.join("textlint-v8.js"),
        "throw new Error('textlint runtime is unavailable in docs.rs builds');\n",
    )
    .context("write docs.rs JavaScript placeholder")?;
    write(
        out_dir.join("THIRD_PARTY_NOTICES.txt"),
        "Third-party notices are generated by normal textlint-v8 builds.\n",
    )
    .context("write docs.rs notice placeholder")?;

    let dictionary_dir = out_dir.join("kuromoji");
    create_dir_all(&dictionary_dir).context("create docs.rs dictionary placeholder directory")?;
    for filename in DICTIONARY_FILES {
        write(dictionary_dir.join(filename), [])
            .with_context(|| format!("write docs.rs dictionary placeholder {filename}"))?;
    }
    Ok(())
}
